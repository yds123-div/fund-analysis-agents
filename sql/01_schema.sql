-- 1. User
CREATE TABLE IF NOT EXISTS TM_USER
(
    ID               BIGINT PRIMARY KEY AUTO_INCREMENT,
    USERNAME         VARCHAR(50) NOT NULL,
    NICKNAME         VARCHAR(50),
    EMAIL            VARCHAR(100),
    PHONE            VARCHAR(20),
    PASSWORD_HASH    VARCHAR(255),
    ROLE             VARCHAR(20) NOT NULL DEFAULT 'USER',
    STATUS           TINYINT     NOT NULL DEFAULT 1,
    LAST_LOGIN_TIME  DATETIME,
    LOGIN_FAIL_COUNT INT                  DEFAULT 0,
    LOCK_UNTIL       DATETIME,
    CREATED_AT       DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT       DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UK_USER_USERNAME (USERNAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='User account';

-- 2. User Profile
CREATE TABLE IF NOT EXISTS TM_USER_PROFILE
(
    ID                       BIGINT PRIMARY KEY AUTO_INCREMENT,
    USER_ID                  BIGINT        NOT NULL,
    RISK_LEVEL               VARCHAR(20)   NOT NULL DEFAULT 'BALANCED',
    INVESTMENT_HORIZON       VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
    MAX_DRAWDOWN_TOLERANCE   DECIMAL(5, 2) NOT NULL DEFAULT 20.00,
    PREFERRED_INDUSTRIES     JSON,
    AVOIDED_INDUSTRIES       JSON,
    FUND_SCALE_PREFERENCE    VARCHAR(20)   NOT NULL DEFAULT 'ANY',
    TURNOVER_TOLERANCE       VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
    ACCEPT_NEW_FUND          TINYINT       NOT NULL DEFAULT 0,
    CONCENTRATION_PREFERENCE VARCHAR(20)   NOT NULL DEFAULT 'ANY',
    COMPLETED                TINYINT       NOT NULL DEFAULT 0,
    CREATED_AT               DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT               DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UK_PROFILE_USER (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='User investment profile';

-- 3. Fund Info
CREATE TABLE IF NOT EXISTS TM_FUND_INFO
(
    ID                 BIGINT PRIMARY KEY AUTO_INCREMENT,
    FUND_CODE          VARCHAR(10) NOT NULL,
    FUND_NAME          VARCHAR(100),
    FUND_TYPE          VARCHAR(30),
    MANAGEMENT_COMPANY VARCHAR(100),
    FUND_MANAGER       VARCHAR(50),
    ESTABLISH_DATE     DATE,
    FUND_SCALE         DECIMAL(18, 4),
    NAV                DECIMAL(10, 4),
    ACCUMULATED_NAV    DECIMAL(10, 4),
    DAY_GROWTH_RATE    DECIMAL(8, 4),
    SHARPE_RATIO       DECIMAL(8, 4),
    MAX_DRAWDOWN       DECIMAL(8, 4),
    VOLATILITY         DECIMAL(8, 4),
    DATA_UPDATE_TIME   DATETIME,
    CREATED_AT         DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT         DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UK_FUND_CODE (FUND_CODE),
    INDEX              IDX_FUND_TYPE (FUND_TYPE),
    INDEX              IDX_FUND_NAME (FUND_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Fund basic information';

-- 4. Fund Portfolio (includes V5 DIP fields)
CREATE TABLE IF NOT EXISTS TM_FUND_PORTFOLIO
(
    ID             BIGINT PRIMARY KEY AUTO_INCREMENT,
    USER_ID        BIGINT      NOT NULL,
    FUND_CODE      VARCHAR(10) NOT NULL,
    HOLDING_AMOUNT DECIMAL(18, 4),
    AVG_COST       DECIMAL(10, 4),
    PURCHASE_DATE  DATETIME,
    NOTES          VARCHAR(500),
    AUTO_DIP       TINYINT(1)     DEFAULT 0 COMMENT '是否开启定投',
    DIP_AMOUNT     DECIMAL(12, 2)       DEFAULT NULL COMMENT '定投金额',
    DIP_FREQUENCY  VARCHAR(20)          DEFAULT 'MONTHLY' COMMENT '定投频率',
    CREATED_AT     DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT     DATETIME    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UK_PORTFOLIO_USER_FUND (USER_ID, FUND_CODE),
    INDEX          IDX_PORTFOLIO_USER (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='User fund portfolio';

-- 5. Watch List
