-- 7. Task Execution
CREATE TABLE IF NOT EXISTS TM_TASK_EXECUTION
(
    ID                BIGINT PRIMARY KEY AUTO_INCREMENT,
    TASK_ID           BIGINT,
    FUND_CODE         VARCHAR(10),
    FUND_NAME         VARCHAR(100),
    BATCH_NO          VARCHAR(50) NOT NULL,
